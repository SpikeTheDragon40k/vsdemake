#!/usr/bin/env python3
"""Generates engine/src/core/vs_font_data.h: the UI font as a run-length
encoded 4-bit alpha atlas.

The original draws its menus with the browser's default Courier at 16 px
(Phaser's default text style). No font ships with the game, so the demake
uses Liberation Mono (metric-compatible with Courier New, SIL Open Font
License 1.1) rasterized here at a few pixel sizes. The output is a bitmap
version of that font and stays under the OFL (see the header's notice).

    python3 engine/tools/gen_font.py /path/to/LiberationMono-Regular.ttf

Needs Pillow. Sizes are chosen so that one character advances 6 px times
the engine's text scale (Courier's advance is 0.6 em): 10, 15, 20, 30 px
for scales 1, 1.5, 2 and 3.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

SIZES = [10, 15, 20, 30]
FIRST, LAST = 32, 126
ATLAS_W = 512
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'core', 'vs_font_data.h')


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf'
    sizes = []
    rows = []   # (y, size info)
    y = 0
    glyph_rows = []
    for px in SIZES:
        font = ImageFont.truetype(path, px)
        ascent, descent = font.getmetrics()
        adv = round(0.6 * px)
        cell_h = ascent + descent
        per_row = ATLAS_W // adv
        n = LAST - FIRST + 1
        lines = (n + per_row - 1) // per_row
        img = Image.new('L', (ATLAS_W, lines * cell_h), 0)
        d = ImageDraw.Draw(img)
        for i in range(n):
            cx, cy = (i % per_row) * adv, (i // per_row) * cell_h
            d.text((cx, cy), chr(FIRST + i), font=font, fill=255)
        # cap height: rows of 'H' that have ink
        h = Image.new('L', (adv * 2, cell_h), 0)
        ImageDraw.Draw(h).text((0, 0), 'H', font=font, fill=255)
        ink = [r for r in range(cell_h) if any(h.getpixel((c, r)) > 64 for c in range(adv * 2))]
        cap_top = ink[0] if ink else 0
        sizes.append((px, adv, cell_h, ascent, cap_top, y, per_row))
        glyph_rows.append(img)
        y += lines * cell_h
    atlas = Image.new('L', (ATLAS_W, y), 0)
    yy = 0
    for img in glyph_rows:
        atlas.paste(img, (0, yy))
        yy += img.size[1]
    # 4-bit alpha, run-length coded: a byte >= 0x80 is a run of (b & 0x7f) + 1
    # transparent pixels, any other byte one pixel of alpha b × 17
    data = []
    run = 0
    for p in atlas.tobytes():
        a = (p + 8) // 17
        if a == 0:
            run += 1
            if run == 128:
                data.append(0x80 | 127)
                run = 0
            continue
        if run:
            data.append(0x80 | (run - 1))
            run = 0
        data.append(a)
    if run:
        data.append(0x80 | (run - 1))
    with open(OUT, 'w') as f:
        f.write('''/* Generated by engine/tools/gen_font.py. Do not edit.
 *
 * UI font: a bitmap version of Liberation Mono Regular.
 * Digitized data copyright (c) 2010 Google Corporation with Reserved Font
 * Arimo, Tinos and Cousine. Copyright (c) 2012 Red Hat, Inc. with Reserved
 * Font Name Liberation.
 * This Font Software is licensed under the SIL Open Font License, Version
 * 1.1 (engine/src/core/OFL.txt, https://openfontlicense.org). This file,
 * unlike the rest of the project, stays under that license. */
#ifndef VS_FONT_DATA_H
#define VS_FONT_DATA_H
''')
        f.write('#define VS_FONT_ATLAS_W %d\n#define VS_FONT_ATLAS_H %d\n#define VS_FONT_FIRST %d\n#define VS_FONT_LAST %d\n#define VS_FONT_SIZES %d\n' % (ATLAS_W, y, FIRST, LAST, len(SIZES)))
        f.write('/* pixel size, advance, cell height, ascent (baseline), cap top, atlas y, cells per row */\n')
        f.write('static const short VS_FONT_SIZE_INFO[VS_FONT_SIZES][7] = {\n')
        for s in sizes:
            f.write('    { %s },\n' % ', '.join(str(v) for v in s))
        f.write('};\n')
        f.write('static const unsigned char VS_FONT_RLE[%d] = {\n' % len(data))
        for i in range(0, len(data), 24):
            f.write('    ' + ','.join(str(v) for v in data[i:i + 24]) + ',\n')
        f.write('};\n#endif\n')
    print('atlas %dx%d, %d bytes' % (ATLAS_W, y, len(data)))


if __name__ == '__main__':
    main()
