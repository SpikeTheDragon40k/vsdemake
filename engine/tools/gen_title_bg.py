#!/usr/bin/env python3
"""Generates engine/src/game/title_bg_data.h from engine/assets/title_bg.png:
the title screen's background, scaled to the 810 x 456 screen and stored
as a JPEG (decoded at start-up by stb_image).

    python3 engine/tools/gen_title_bg.py [image]

Needs Pillow.
"""
import io
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'assets', 'title_bg.png')
OUT = os.path.join(HERE, '..', 'src', 'game', 'title_bg_data.h')
W, H = 810, 456


def main():
    img = Image.open(sys.argv[1] if len(sys.argv) > 1 else SRC).convert('RGB')
    img = img.resize((W, H), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, 'JPEG', quality=90, subsampling=0, optimize=True)   # baseline JPEG
    data = buf.getvalue()
    with open(OUT, 'w') as f:
        f.write('/* Generated by engine/tools/gen_title_bg.py from engine/assets/title_bg.png. Do not edit. */\n')
        f.write('#ifndef VS_TITLE_BG_DATA_H\n#define VS_TITLE_BG_DATA_H\n')
        f.write('static const unsigned char VS_TITLE_BG_JPG[%d] = {\n' % len(data))
        for i in range(0, len(data), 24):
            f.write('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',\n')
        f.write('};\n#endif\n')
    print('%dx%d JPEG, %d bytes' % (W, H, len(data)))


if __name__ == '__main__':
    main()
