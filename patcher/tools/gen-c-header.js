'use strict';
// Generates engine/src/core/vs_tables.h (record structs, from tables.js) and
// engine/src/core/vs_enums.h (enum member names, from an extracted
// enums.json). Usage: node patcher/tools/gen-c-header.js [work/out/data/enums.json]
//
// The enums header holds identifier names only (WHIP, ANTONIO, …), no game
// values, so both headers are committed.

const fs = require('fs');
const path = require('path');
const { TABLES, resolveEnums } = require('../src/tables');
const { ENUM_NAMES } = require('../src/pack');

const OUT = path.join(__dirname, '..', '..', 'engine', 'src', 'core');
const cType = (type) => {
  const kind = type.split(':')[0];
  return kind === 'f32' ? 'float' : kind === 'i32' || kind === 'bool' || kind === 'enum' ? 'int32_t' : 'uint32_t';
};
const upper = (s) => s.replace(/[^A-Za-z0-9]/g, '_').toUpperCase();

function structFor(cname, fields) {
  let s = `typedef struct {\n    uint64_t present;\n`;
  for (const [f, type] of fields) s += `    ${cType(type)} ${f};\n`;
  s += `} vs_${cname}_rec;\n`;
  s += `enum { ${fields.map(([f], i) => `VS_${upper(cname)}_F_${upper(f)} = ${i}`).join(', ')} };\n`;
  s += `#define VS_${upper(cname)}_FIELDS ${fields.length}\n`;
  s += `#define VS_${upper(cname)}_FIELD_NAMES ${JSON.stringify(fields.map(([f]) => f).join(','))}\n\n`;
  return s;
}

let h = `/* Generated by patcher/tools/gen-c-header.js from patcher/src/tables.js. Do not edit. */
#ifndef VS_TABLES_H
#define VS_TABLES_H
#include <stdint.h>

/* Each record starts with a presence mask: bit i set means field i was present
 * in the source data. Absent numeric fields read as 0. Strings and lists are
 * byte offsets into the table's string table / pool (vs_pack.h). */
#define VS_HAS(rec, field_enum) (((rec)->present >> (field_enum)) & 1u)

`;
for (const [name, def] of Object.entries(TABLES)) {
  h += structFor(name, def.fields);
  for (const [sname, sdef] of Object.entries(def.sub || {})) h += structFor(`${name}_${sname}`, sdef.fields);
}
h += '#endif\n';
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'vs_tables.h'), h);

const enumsPath = process.argv[2] || path.join(__dirname, '..', '..', 'work', 'out', 'data', 'enums.json');
if (fs.existsSync(enumsPath)) {
  const enums = resolveEnums(JSON.parse(fs.readFileSync(enumsPath, 'utf8')));
  let e = `/* Generated by patcher/tools/gen-c-header.js. Member names in declaration order. Do not edit. */
#ifndef VS_ENUMS_H
#define VS_ENUMS_H

`;
  for (const [key, en] of Object.entries(enums)) {
    const short = ENUM_NAMES[key] || key;
    e += `enum vs_${short} {\n${en.names.map((n, i) => `    VS_${upper(short)}_${upper(n)} = ${i},`).join('\n')}\n    VS_${upper(short)}_COUNT = ${en.names.length}\n};\n\n`;
  }
  e += '#endif\n';
  fs.writeFileSync(path.join(OUT, 'vs_enums.h'), e);
  console.log('wrote vs_tables.h, vs_enums.h');
} else {
  console.log('wrote vs_tables.h (no enums.json, vs_enums.h skipped)');
}
